"use client";

// ログイン状態が変わったあとの画面遷移（指示書162）
//
// 【なぜ router.push ではなく、画面ごと読み込み直すのか】
//
// Next.js の <Link> は本番でリンク先を**自動的に先読み（プリフェッチ）**する。
// 未ログインで開ける画面（/login・/join・/reset-password）から、ログインが必要な
// 画面へのリンクが1本でもあると、**まだログインしていない時点の判定**
// ＝ proxy.ts が返す「/login への307リダイレクト」が先読みされ、
// クライアント側のルーターキャッシュに記録される。
//
// このアプリには loading.tsx が1つも無い。Next.js の「Prefetching」の表では
// この場合の Client Cache TTL は **Until app reload（アプリを読み込み直すまで）**。
// つまり一度記録された「/ はログイン画面へ」という判定が、そのタブが生きている間
// ずっと残り続ける。
//
// 実際に起きたこと（2026-08-15 院長の実機確認・指示書162）:
//   1. 未ログインで /join を開く（このとき / への先読みが走り、307が記録される）
//   2. 招待コードで登録 → 自動ログイン成功（**Cookieは正しく発行されている**）
//   3. /profile には入れる（先読みされていないのでサーバーに問い合わせる）
//   4. メニューの「ホーム」を押す → **サーバーに問い合わせないまま**、記録済みの
//      「/ はログイン画面へ」が使われ、ログイン画面に戻される
//
// つまりセッションは最初から正常で、クライアント側のキャッシュだけが
// ログイン前の判定を持ち越していた。router.refresh() ではこのキャッシュを
// 確実に捨てられない（先読み分が残る）。
//
// よって **ログイン・登録・ログアウトの直後だけは画面ごと読み込み直す。**
// ここを通れば、それ以前に記録された判定はすべて破棄される。
// 認証をまたぐ遷移は多くても1人1日数回で、体感上の不利はほぼない。
//
// replace を使う理由: 戻るボタンで登録画面・ログイン画面に戻さないため。
//
// ※ これは「未認証を通す」変更ではない。proxy.ts の既定拒否（161）はそのまま。
//    有効なセッションを正しく認識させるための、クライアント側の後始末である。

/** ログイン状態が変わったあとの遷移。ルーターキャッシュを捨てるため画面ごと読み込む */
export function reloadTo(path: string): void {
  if (typeof window === "undefined") return;
  window.location.replace(path);
}
